#!/usr/bin/env python3
"""Writes check/stubs-hosted.sql: a copy of the repo's supabase/tests/stubs.sql
(never edited) with auth.users replaced by a table shaped like hosted
Supabase Auth's (GoTrue) and auth.identities, the extensions schema with
pgcrypto, and a vault stand-in, so 90-test-accounts.sql can be checked
against the columns, defaults, NOT NULLs and unique indexes it meets there.
Usage: python3 -I make_hosted_stubs.py <repo stubs.sql> <out file>
"""
import sys

GOTRUE_USERS = """create table auth.users (
  instance_id uuid,
  id uuid not null primary key,
  aud varchar(255),
  role varchar(255),
  email varchar(255),
  encrypted_password varchar(255),
  email_confirmed_at timestamptz,
  invited_at timestamptz,
  confirmation_token varchar(255),
  confirmation_sent_at timestamptz,
  recovery_token varchar(255),
  recovery_sent_at timestamptz,
  email_change_token_new varchar(255),
  email_change varchar(255),
  email_change_sent_at timestamptz,
  last_sign_in_at timestamptz,
  raw_app_meta_data jsonb,
  raw_user_meta_data jsonb,
  is_super_admin boolean,
  created_at timestamptz,
  updated_at timestamptz,
  phone text unique default null,
  phone_confirmed_at timestamptz,
  phone_change text default '',
  phone_change_token varchar(255) default '',
  phone_change_sent_at timestamptz,
  confirmed_at timestamptz generated always as (least(email_confirmed_at, phone_confirmed_at)) stored,
  email_change_token_current varchar(255) default '',
  email_change_confirm_status smallint default 0 check (email_change_confirm_status >= 0 and email_change_confirm_status <= 2),
  banned_until timestamptz,
  reauthentication_token varchar(255) default '',
  reauthentication_sent_at timestamptz,
  is_sso_user boolean not null default false,
  deleted_at timestamptz,
  is_anonymous boolean not null default false
);
create index users_instance_id_idx on auth.users (instance_id);
create index users_instance_id_email_idx on auth.users (instance_id, lower(email::text));
create unique index confirmation_token_idx on auth.users (confirmation_token) where confirmation_token::text !~ '^[0-9 ]*$';
create unique index recovery_token_idx on auth.users (recovery_token) where recovery_token::text !~ '^[0-9 ]*$';
create unique index email_change_token_current_idx on auth.users (email_change_token_current) where email_change_token_current::text !~ '^[0-9 ]*$';
create unique index email_change_token_new_idx on auth.users (email_change_token_new) where email_change_token_new::text !~ '^[0-9 ]*$';
create unique index reauthentication_token_idx on auth.users (reauthentication_token) where reauthentication_token::text !~ '^[0-9 ]*$';
create unique index users_email_partial_key on auth.users (email) where is_sso_user = false;
create index users_is_anonymous_idx on auth.users (is_anonymous);
create table auth.identities (
  provider_id text not null,
  user_id uuid not null references auth.users (id) on delete cascade,
  identity_data jsonb not null,
  provider text not null,
  last_sign_in_at timestamptz,
  created_at timestamptz,
  updated_at timestamptz,
  email text generated always as (lower(identity_data ->> 'email')) stored,
  id uuid not null default gen_random_uuid() primary key,
  constraint identities_provider_id_provider_unique unique (provider_id, provider)
);
create index identities_user_id_idx on auth.identities (user_id);
create index identities_email_idx on auth.identities (email text_pattern_ops);
-- Hosted Supabase keeps pgcrypto and uuid-ossp in the extensions schema,
-- and has Vault (no secrets in a new project). pg_net and pg_cron are off.
create schema extensions;
create extension pgcrypto with schema extensions;
create extension "uuid-ossp" with schema extensions;
create schema vault;
create table vault.secrets (id uuid primary key default gen_random_uuid(), name text unique, description text, secret text);
create view vault.decrypted_secrets as select id, name, description, secret, secret as decrypted_secret from vault.secrets;"""


def main():
    src, out = sys.argv[1], sys.argv[2]
    lines = open(src, encoding="utf-8").read().split("\n")
    hits = [i for i, l in enumerate(lines) if l.startswith("create table auth.users ")]
    if len(hits) != 1:
        sys.exit("make_hosted_stubs.py: expected exactly one 'create table auth.users' line in " + src)
    lines[hits[0]] = GOTRUE_USERS
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("-- GENERATED by check/make_hosted_stubs.py from the repo's supabase/tests/stubs.sql.\n"
                 "-- Local checking only: never run this on Supabase.\n" + "\n".join(lines))


if __name__ == "__main__":
    main()
